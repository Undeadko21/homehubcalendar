// Значок события по словам в названии и месте (настройка «Значки событий» во «Внешнем виде»).
// Порядок важен: первое совпадение побеждает. Без учёта регистра. «\b» в JavaScript не видит границ русских слов,
// поэтому целые короткие слова помечены как <слово>: они превращаются в проверку «не буква» по краям.
import { state } from './store'

const L = 'а-яёa-z'
const w = (src) => new RegExp(src.replace(/<([^>]+)>/g, `(?:^|[^${L}])$1(?![${L}])`))

const RULES = [
  [w('день рождени|<др>|birthday|юбиле'), '🎂'],
  [/бассейн|плаван|аквапарк/, '🏊'],
  [/врач|поликлиник|больниц|стоматолог|зубн|педиатр|анализ|прививк|клиник|медосмотр/, '🩺'],
  [/футбол/, '⚽'], [/хокке/, '🏒'], [/баскетбол|волейбол/, '🏀'], [/теннис/, '🎾'],
  [w('тренировк|спорт|фитнес|<зал[аеу]?>|йог|<бег>|пробежк|гимнастик|секци'), '🏋️'],
  [/танц|хореограф|балет/, '💃'], [w('музык|фортепиан|гитар|вокал|<хор[аеу]?>|скрипк'), '🎵'],
  [w('рисован|художеств|<изо>|лепк'), '🎨'], [/шахмат/, '♟️'],
  [/школ|урок|собрани|олимпиад|репетитор|английск|математик|кружок/, '📚'],
  [w('детск\\w* сад|садик|<сад>'), '🧸'],
  [/самол[её]т|рейс|аэропорт|вылет|перел[её]т/, '✈️'], [/поезд|вокзал|электричк/, '🚆'],
  [/отпуск|каникул|поездк|путешеств/, '🧳'],
  [/ресторан|кафе|ужин|обед|завтрак/, '🍽️'], [/кино|театр|концерт|спектакл|цирк|музей/, '🎭'],
  [/магазин|покупк|закупк/, '🛒'], [/стрижк|парикмахер|барбер|маникюр/, '💇'],
  [w('машин|шиномонтаж|автосервис|<то>|техосмотр'), '🚗'], [w('ветеринар|<вет>|собак|кошк'), '🐾'],
  [/созвон|звонок|встреч|совещани|митинг|планерк|zoom|teams/, '💼'],
  [/гости|в гостях|праздник|вечеринк/, '🎉'], [/дача|даче/, '🏡'],
]

export function eventIcon(e) {
  if (!e || e.private) return ''
  if (e.birthday) return '🎂'
  const text = ((e.title || '') + ' ' + (e.location || '')).toLowerCase()
  for (const [re, icon] of RULES) if (re.test(text)) return icon
  return ''
}

/** Название со значком спереди, если значки включены. */
export function titleWithIcon(e) {
  const i = state.icons ? eventIcon(e) : ''
  return i ? `${i} ${e.title}` : e.title
}
