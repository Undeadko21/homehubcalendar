// Читаемый цвет текста на насыщенной плашке («весь день»): на жёлтом, оранжевом, зелёном, бирюзовом — тёмный, на остальных — белый.
export function onColor(c) {
  const m = /^#?([0-9a-f]{6})$/i.exec(String(c || '').trim())
  if (!m) return '#fff'
  const v = [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16) / 255)
    .map((x) => (x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4))
  const lum = 0.2126 * v[0] + 0.7152 * v[1] + 0.0722 * v[2]
  return lum > 0.36 ? '#1d1d1f' : '#fff'
}
