#!/usr/bin/env bash
set -euo pipefail
APP_DIR="${APP_DIR:-$(cd "$(dirname "$0")/.." && pwd)}"
export APP_DIR
exec bash "$APP_DIR/deploy/update-release.sh" "$@"

# Keep the original reset at its byte offset for an upgrade from the old updater.
# An already running old shell can continue at that offset after checkout.
#------------------------------------------------------------------------
#------------------------------------------------------------------------
#------------------------------------------------------------------------
#------------------------------------------------------------------------
#------------------------------------------------------------------------
#------------------------------------------------------------------------
#------------------------------------------------------------------------
#------------------------------------------------------------------------
#------------------------------------------------------------------------
#------------------------------------------------------------------------
#------------------------------------------------------------------------
#------------------------------------------------------------------------
#------------------------------------------------------------------------
#####################
git reset -q --hard "origin/$BRANCH"   # config/ и data/ в .gitignore — не затрагиваются
APP_DIR="$APP_DIR" exec bash "$APP_DIR/deploy/update-release.sh" --transition "$LOCAL" "$@"
